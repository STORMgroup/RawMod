#!/usr/bin/env python3
"""Supplementary table of test-set composition: modified and unmodified positions per source inside the withheld regions, with the per-source AUROC."""
import os as _os
from pathlib import Path as _Path
REPO = str(_Path(__file__).resolve().parents[2])
RAWMOD_RESULTS = _os.environ.get('RAWMOD_RESULTS') or f'{REPO}/paper/data/runs'  # training runs; shipped metrics by default
RAWMOD_DATA = _os.environ.get('RAWMOD_DATA', 'data')  # datasets (not shipped: set this to score raw signal)
RAWMOD_WORK = _os.environ.get('RAWMOD_WORK') or f'{REPO}/paper/data/work'  # outputs of the paper scripts; shipped by default

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

sys.path.insert(0, str(Path(__file__).resolve().parent))
from region_sites_analyze import test_mask, dataset, EXT_GROUP  # noqa: E402

FOLDS = [('mixed', r'\configmixed'), ('loco_5mC', '5mC'), ('loco_5hmC', '5hmC'), ('loco_6mA', '6mA'),
         ('loco_4mC', '4mC'), ('loco_5hmU', '5hmU')]
SOURCE = {'ONT::': 'ONT oligonucleotides', 'SPO1::': r'\phage', 'HP::': r'\textit{H.~pylori} 26695'}
EXT = {'E. coli': r'\textit{E.~coli}', 'A. thaliana': r'\textit{A.~thaliana}', 'human': 'HG001 + HG002'}
SEEDS = ['s42', 's43', 's44']


def fmt(n):
    return f'{n:,}'


def mean_auroc(y, scores):
    if not 0 < y.sum() < len(y):
        return None
    return float(np.mean([roc_auc_score(y, sc) for sc in scores]))


def main(scores_dir, out):
    d = Path(scores_dir)
    s = pd.read_csv(d / 'sites.tsv.gz', sep='\t', keep_default_na=False, dtype={'chem': str})
    s['dataset'] = s.member.map(dataset)
    s['ext'] = s.dataset.map(EXT_GROUP)
    s['src'] = [EXT.get(e) if isinstance(e, str) else SOURCE.get(o, o) for e, o in zip(s.ext, s.org)]
    L = [r'% GENERATED by figures/make_region_sites_table.py; do not edit by hand.',
         r'\setlength{\tabcolsep}{4pt}%',
         r'\begin{tabular}{@{}l l rrr@{}}', r'\toprule',
         r'\textbf{Held out} & \textbf{Source} & \textbf{Pos.} & \textbf{Neg.} & \textbf{AUROC} \\', r'\midrule']
    summary = []
    for fold, label in FOLDS:
        sc = [pd.read_csv(d / f'{fold}_{x}.tsv.gz', sep='\t').set_index('site').score.reindex(s.site).to_numpy()
              for x in SEEDS]
        t2 = test_mask(s, fold, 'inreg').to_numpy()
        extra = test_mask(s, fold, 'inreg+ext').to_numpy() & ~t2
        y = s.label.to_numpy()
        first = True
        for src in list(SOURCE.values()) + list(EXT.values()):
            for m, paren in ((t2, False), (extra, True)):
                m = m & (s.src == src).to_numpy()
                if not m.any():
                    continue
                a = mean_auroc(y[m], [x[m] for x in sc])
                p, n = fmt(int(y[m].sum())), fmt(int((y[m] == 0).sum()))
                cells = [f'({p})', f'({n})', f'({a:.3f})' if a is not None else '--'] if paren else \
                        [p, n, f'{a:.3f}' if a is not None else '--']
                L.append(f'{label if first else ""} & {src} & ' + ' & '.join(cells) + r' \\')
                first = False
        a = mean_auroc(y[t2], [x[t2] for x in sc])
        L.append(rf' & \textit{{all (\cref{{tab:loco}})}} & {fmt(int(y[t2].sum()))} & {fmt(int((y[t2] == 0).sum()))} & {a:.3f} \\')
        summary.append((fold, int(y[t2].sum()), int((y[t2] == 0).sum()), a))
        if fold != FOLDS[-1][0]:
            L.append(r'\midrule')
    L += [r'\bottomrule', r'\end{tabular}']
    Path(out).write_text('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    if len(sys.argv) < 3:
        sys.exit('usage: make_region_sites_table.py SCORES_DIR OUT.tex\n'
                 '  SCORES_DIR holds the per-site scores of score_holdout_region.py, which are\n'
                 '  not shipped with the repository (see paper/README.md).')
    main(*sys.argv[1:3])
