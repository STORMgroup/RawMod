# support-half positive sites per fold on the holdout tree (from the [fewshot] log lines); K above this is capped
SUPPORT_POS = {'loco_5hmU': 10173, 'loco_5mC': 10 ** 9, 'loco_5hmC': 10 ** 9, 'loco_4mC': 10 ** 9, 'loco_6mA': 17366}


def region_metrics(fold, seed=42):
    """row of the region-holdout metrics (all_neg variant) for one fold and seed, or None"""
    if fold == 'mixed':
        p = RES / f'region_mixed{SEEDS[seed]}_region_score' / 'metrics' / 'mixed.tsv'
    else:
        p = RES / f'region_loco{SEEDS[seed]}_region_score' / 'metrics' / f'{fold}.tsv'
    if not p.exists():
        return None
    d = pd.read_csv(p, sep='\t')
    d = d[d.test_set.str.endswith('all_neg')]
    return d.iloc[0] if len(d) else None


def seed_stats(fold, col='auroc'):
    v = [float(r[col]) for r in (region_metrics(fold, s) for s in SEEDS) if r is not None]
    return (np.mean(v), np.min(v), np.max(v), len(v)) if v else (np.nan, np.nan, np.nan, 0)


def save(fig, name):
    fig.savefig(HERE / name, bbox_inches='tight', pad_inches=0.02)
    fig.savefig(HERE / name.replace('.pdf', '.png'), dpi=250, bbox_inches='tight', pad_inches=0.02)
    plt.close(fig)
    print('wrote', HERE / name)


def loco_table():
    rows = []
    for c in ['mixed'] + CHEMS:
        f = 'mixed' if c == 'mixed' else f'loco_{c}'
        m, lo, hi, n = seed_stats(f)
        ap = seed_stats(f, 'auprc')[0]
        r = region_metrics(f)
        rows.append((c, m, lo, hi, n, ap, float(r.n_pos) / float(r.n_test), int(r.n_pos), int(r.n_test) - int(r.n_pos)))
    L = [r'\setlength{\tabcolsep}{3pt}%',
         r'\begin{tabular}{@{}l S[table-format=1.3] c S[table-format=1.3] S[table-format=1.2] r r@{}}', r'\toprule',
         r'\textbf{Held out} & {\textbf{AUROC}} & \textbf{Range (3 seeds)} & {\textbf{AUPRC}} & {\textbf{$\pi$}} & $n_{+}$ & $n_{-}$ \\',
         r'\midrule']
    for i, (c, m, lo, hi, n, ap, pi, npos, nneg) in enumerate(rows):
        name = r'\configmixed' if c == 'mixed' else c
        L.append(f'{name} & {m:.3f} & {lo:.3f}--{hi:.3f} & {ap:.3f} & {pi:.2f} & {npos:,} & {nneg:,} \\\\')
        if i == 0:
            L.append(r'\midrule')
    L += [r'\midrule', f'\\textit{{mean (LOCO)}} & {np.mean([r[1] for r in rows[1:]]):.3f} & & {np.mean([r[5] for r in rows[1:]]):.3f} & & & \\\\',
          r'\bottomrule', r'\end{tabular}']
    out = P.TABLES / 'loco_results_region.tex'; out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('% GENERATED by figures/make_region_figures.py from the region-holdout runs; do not edit by hand.\n' + '\n'.join(L) + '\n')
    print('wrote', out); print('\n'.join(L))


