#!/usr/bin/env python3
"""Supplementary table of the no-learning baseline, next to the model, from baseline.tsv."""
import os as _os
from pathlib import Path as _Path
REPO = str(_Path(__file__).resolve().parents[2])
RAWMOD_RESULTS = _os.environ.get('RAWMOD_RESULTS') or f'{REPO}/paper/data/runs'  # training runs; shipped metrics by default
RAWMOD_DATA = _os.environ.get('RAWMOD_DATA', 'data')  # datasets (not shipped: set this to score raw signal)
RAWMOD_WORK = _os.environ.get('RAWMOD_WORK') or f'{REPO}/paper/data/work'  # outputs of the paper scripts; shipped by default

import pandas as pd
from pathlib import Path
RES = Path(f'{RAWMOD_RESULTS}')
b = pd.read_csv(Path(__file__).parent / 'baseline.tsv', sep='\t')
b = b[b.test_set == 'all_neg'].set_index('fold')
NAME = {'mixed': r'\configmixed (all modifications)', 'loco_5mC': '5mC held out', 'loco_5hmC': '5hmC held out',
        'loco_6mA': '6mA held out', 'loco_4mC': '4mC held out', 'loco_5hmU': '5hmU held out'}
L = [r'% GENERATED by paper/supp_ablations/make_table.py from baseline.tsv; do not edit by hand.',
     r'\setlength{\tabcolsep}{4pt}%', r'\begin{tabular}{@{}l rr c cccc@{}}', r'\toprule',
     r'\textbf{Model} & $n_{+}$ & $n_{-}$ & \textbf{\sysname} & \textbf{$|\Delta|$ at base} & \textbf{$\Delta$ at base} & '
     r'\textbf{window $|\Delta|$} & \textbf{side fraction} \\', r'\midrule']
for f, nm in NAME.items():
    p = RES / ('region_mixed_region_score' if f == 'mixed' else 'region_loco_region_score') / 'metrics' / f'{f}.tsv'
    m = pd.read_csv(p, sep='\t'); m = m[m.test_set.str.endswith('all_neg')].iloc[0]
    assert int(m.n_pos) == int(b.n_pos[f]) and int(m.n_test) == int(b.n_test[f]), (f, m.n_test, b.n_test[f])
    r = b.loc[f]
    L.append(f'{nm} & {int(r.n_pos):,} & {int(r.n_test - r.n_pos):,} & {m.auroc:.3f} & {r.dctr_abs:.3f} & {r.dctr:.3f} & '
             f'{r.dwin_abs:.3f} & {r.ks_ctr:.3f} \\\\')
L += [r'\bottomrule', r'\end{tabular}']
out = Path(_os.environ.get('RAWMOD_TABLES') or f'{REPO}/paper/tables') / 'supp_nolearn.tex'
out.write_text('\n'.join(L) + '\n'); print('\n'.join(L))
