#!/usr/bin/env python3
"""Supplementary ablation table: AUROC of every ablated configuration (one run per row, plus seed replicates for the final configuration and three ablations) inside the withheld regions."""
import os as _os
from pathlib import Path as _Path
REPO = str(_Path(__file__).resolve().parents[2])
RAWMOD_RESULTS = _os.environ.get('RAWMOD_RESULTS') or f'{REPO}/paper/data/runs'  # training runs; shipped metrics by default
RAWMOD_DATA = _os.environ.get('RAWMOD_DATA', 'data')  # datasets (not shipped: set this to score raw signal)
RAWMOD_WORK = _os.environ.get('RAWMOD_WORK') or f'{REPO}/paper/data/work'  # outputs of the paper scripts; shipped by default

import sys
from pathlib import Path
import pandas as pd
TABLES = Path(_os.environ.get('RAWMOD_TABLES') or f'{REPO}/paper/tables')

RES = Path(f'{RAWMOD_RESULTS}')
FOLDS = ['mixed', 'loco_5mC', 'loco_5hmC', 'loco_6mA', 'loco_4mC', 'loco_5hmU']


def final_dir(fold, sfx):
    return f'region_mixed{sfx}_region_score' if fold == 'mixed' else f'region_loco{sfx}_region_score'


ROWS = [  # (group header or None, label, run-directory function of fold)
    (None, r'\sysname (final, seed 42)', lambda f: final_dir(f, '')),
    (None, r'\hspace{4pt}seed 43', lambda f: final_dir(f, '_s43')),
    (None, r'\hspace{4pt}seed 44', lambda f: final_dir(f, '_s44')),
    ('Input features', r'$-$ site-deviation channel', lambda f: 'ablation_noch9_region_score'),
    (None, r'\hspace{4pt}seed 43', lambda f: 'ablation_noch9_s43_region_score'),
    (None, r'\hspace{4pt}seed 44', lambda f: 'ablation_noch9_s44_region_score'),
    (None, r'Base identity masked', lambda f: 'ablation_maskbases_region_score'),
    ('Architecture', r'No cross-read Transformer (mean-pooled read tokens)', lambda f: 'ablation_notf_region_score'),
    (None, r'1 Transformer layer', lambda f: 'ablation_tf1_region_score'),
    (None, r'4 Transformer layers', lambda f: 'ablation_tf4_region_score'),
    (None, r'$-$ learned row embedding', lambda f: 'ablation_norowemb_region_score'),
    ('Training objective', r'$-$ supervised contrastive loss', lambda f: 'ablation_nosupcon_region_score'),
    (None, r'$-$ Deep SAD loss', lambda f: 'ablation_nosad_region_score'),
    (None, r'$-$ both (classification loss only)', lambda f: 'ablation_bce_region_score'),
    (None, r'\hspace{4pt}seed 43', lambda f: 'ablation_bce_s43_region_score'),
    (None, r'\hspace{4pt}seed 44', lambda f: 'ablation_bce_s44_region_score'),
    (None, r'Deep SAD width 64', lambda f: 'ablation_sad64_region_score'),
    ('Training data', r'$-$ curriculum (no matched-only stage)', lambda f: 'ablation_nocur_region_score'),
    (None, r'\hspace{4pt}seed 43', lambda f: 'ablation_nocur_s43_region_score'),
    (None, r'\hspace{4pt}seed 44', lambda f: 'ablation_nocur_s44_region_score'),
]


def auroc(run, fold):
    p = RES / run / 'metrics' / f'{fold}.tsv'
    if not p.exists():
        return None
    d = pd.read_csv(p, sep='\t')
    d = d[d.test_set.str.endswith('all_neg')]
    return float(d['auroc'].iloc[0]) if len(d) else None


def main(out):
    lines = [r'% GENERATED by figures/make_ablation_table_region.py; do not edit by hand.',
             r'\setlength{\tabcolsep}{3.5pt}%',
             r'\begin{tabular}{@{}l c ccccc c@{}}', r'\toprule',
             r'\textbf{Configuration} & \textbf{\configmixed} & \textbf{5mC} & \textbf{5hmC} & \textbf{6mA} & '
             r'\textbf{4mC} & \textbf{5hmU} & \textbf{Mean} \\', r'\midrule']
    for group, label, run in ROWS:
        if group:
            lines += [r'\midrule', rf'\multicolumn{{8}}{{@{{}}l}}{{\textit{{{group}}}}} \\']
        v = [auroc(run(f), f) for f in FOLDS]
        cells = [f'{x:.3f}' if x is not None else r'\tbd{--}' for x in v]
        loco = v[1:]
        mean = f'{sum(loco) / 5:.3f}' if all(x is not None for x in loco) else r'\tbd{--}'
        indent = '' if label.startswith(r'\sysname') or label.startswith(r'\hspace') else r'\hspace{4pt}'
        lines.append(f'{indent}{label} & ' + ' & '.join(cells) + f' & {mean} \\\\')
        print(f'{label[:44]:44s}', ' '.join(f'{x:.3f}' if x is not None else '  -  ' for x in v), mean)
    lines += [r'\bottomrule', r'\end{tabular}']
    Path(out).write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else str(TABLES / 'supp_ablations.tex'))
