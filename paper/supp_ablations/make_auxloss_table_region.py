#!/usr/bin/env python3
"""Supplementary table comparing the final objective with the classification loss alone: site-embedding separation on the mixed test set and zero-shot AUROC per withheld modification. Reads the outputs of auxloss_embed_arms.py, auxloss_metrics.py and auxloss_loco_boot.py."""
import os as _os
from pathlib import Path as _Path
REPO = str(_Path(__file__).resolve().parents[2])
RAWMOD_RESULTS = _os.environ.get('RAWMOD_RESULTS') or f'{REPO}/paper/data/runs'  # training runs; shipped metrics by default
RAWMOD_DATA = _os.environ.get('RAWMOD_DATA', 'data')  # datasets (not shipped: set this to score raw signal)
RAWMOD_WORK = _os.environ.get('RAWMOD_WORK') or f'{REPO}/paper/data/work'  # outputs of the paper scripts; shipped by default

import sys, json
from pathlib import Path
import pandas as pd
TABLES = Path(_os.environ.get('RAWMOD_TABLES') or f'{REPO}/paper/tables')
A = Path(f'{RAWMOD_WORK}/auxloss')
g = pd.read_csv(A / 'mixed_within_group.tsv', sep='\t')
boot = json.load(open(A / 'metrics_mixed.json'))['bootstrap']
lb = json.load(open(A / 'loco_boot.json'))
NAMES = {'HP::A': r'\textit{H.~pylori} 26695, A', 'HP::C': r'\textit{H.~pylori} 26695, C',
         'ONT::A': 'Oligonucleotides, A', 'ONT::C': 'Oligonucleotides, C', 'SPO1::T': r'\phage, T'}
f = g[g.space == 'final'].set_index('group'); b = g[g.space == 'bce'].set_index('group')


def bold_side(metric, boot_key=None):
    hi_f = (f[metric] > b[metric]).all(); hi_b = (b[metric] > f[metric]).all()
    if boot_key:
        x = boot[boot_key]
        sig = x['lo'] > 0 or x['hi'] < 0
        hi_f, hi_b = hi_f and sig, hi_b and sig
    return 'final' if hi_f else ('bce' if hi_b else None)


B = lambda s, on: rf'\textbf{{{s}}}' if on else s
ari = bold_side('km2_ari', 'km2_ari_final_minus_bce'); sil = bold_side('silhouette')
L = [r'% GENERATED by paper/supp_ablations/make_auxloss_table_region.py; do not edit by hand.', r'\setlength{\tabcolsep}{4pt}%',
     r'\begin{tabularx}{\tablewidth}{@{}l *{6}{>{\centering\arraybackslash}X}@{}}', r'\toprule',
     r'\multicolumn{7}{@{}l}{\textbf{(a) Site embedding of the \configmixed model, positions inside the withheld regions}} \\[2pt]',
     r' & & & \multicolumn{2}{c}{\textbf{$k$-means ARI}} & \multicolumn{2}{c}{\textbf{Silhouette}} \\',
     r'\cmidrule(lr){4-5}\cmidrule(lr){6-7}',
     r'\textbf{Dataset, base} & \textbf{Mod.} & \textbf{Unmod.} & Final & Class.\ only & Final & Class.\ only \\', r'\midrule']
for k, name in NAMES.items():
    L.append(f'{name} & {int(f.n_pos[k]):,} & {int(f.n_neg[k]):,} & ' +
             f"{B(f'{f.km2_ari[k]:.3f}', ari == 'final')} & {B(f'{b.km2_ari[k]:.3f}', ari == 'bce')} & "
             f"{B(f'{f.silhouette[k]:.3f}', sil == 'final')} & {B(f'{b.silhouette[k]:.3f}', sil == 'bce')} \\\\")
CHEMS = ['5mC', '5hmC', '4mC', '6mA', '5hmU']
L += [r'\midrule\addlinespace', r'\multicolumn{7}{@{}l}{\textbf{(b) Withheld modification (\configloco models), zero-shot AUROC of the classifier logit}} \\[2pt]',
      r'\multicolumn{2}{@{}l}{\textbf{Objective}} & ' + ' & '.join(rf'\textbf{{{c}}}' for c in CHEMS) + r' \\', r'\midrule']
row = {'final': [], 'bce': []}
s = pd.read_csv(A / 'loco_summary.tsv', sep='\t')
for chem in CHEMS:
    fold = f'loco_{chem}'
    val = {}
    for arm in ('final', 'bce'):
        r = s[(s.fold == fold) & (s.space == arm)]
        val[arm] = float(r.logit_auroc.iloc[0]) if r is not None and len(r) else None
    if None in val.values():
        sys.exit(f'loco_summary.tsv layout not recognised: {list(s.columns)}')
    d = lb[fold]['logit_final_minus_bce']; sig = d['lo'] > 0 or d['hi'] < 0
    vf, vb = f"{val['final']:.3f}", f"{val['bce']:.3f}"
    row['final'].append(B(vf, sig and d['point'] > 0)); row['bce'].append(B(vb, sig and d['point'] < 0))
L += [r'\multicolumn{2}{@{}l}{Final} & ' + ' & '.join(row['final']) + r' \\',
      r'\multicolumn{2}{@{}l}{Classification only} & ' + ' & '.join(row['bce']) + r' \\']
L += [r'\bottomrule', r'\end{tabularx}']
out = Path(sys.argv[1]) if len(sys.argv) > 1 else TABLES / 'supp_auxloss.tex'
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text('\n'.join(L) + '\n'); print('\n'.join(L)); print('wrote', out)
