#!/usr/bin/env python3
"""Supplementary table: the region-holdout RawMod model on the same reads basecalled with three Dorado models (sup, hac, fast), each with and without Remora's level-table refinement of the segment boundaries. Reads the output of test/benchmark/bench/compare_inputs.py."""
import os as _os
from pathlib import Path as _Path
REPO = str(_Path(__file__).resolve().parents[2])
RAWMOD_WORK = _os.environ.get('RAWMOD_WORK') or f'{REPO}/paper/data/work'  # outputs of the paper scripts; shipped by default

import sys
from pathlib import Path
import pandas as pd

SRC = Path(f'{RAWMOD_WORK}/basecallers/compare_basecallers_refinement.tsv')
TABLES = Path(_os.environ.get('RAWMOD_TABLES') or f'{REPO}/paper/tables')
ROWS = [('ecoli_dam_6mA_reg', r'\textit{E.~coli} Dam 6mA'), ('ecoli_dcm_5mC_reg', r'\textit{E.~coli} Dcm 5mC'),
        ('ecoli_mssi_5mC_reg', r'\textit{E.~coli} M.SssI 5mC'), ('anabaena_6mA_reg', r'\textit{Anabaena} 6mA'),
        ('hp26695_4mC_reg', r'\textit{H.~pylori} 4mC'), ('hp26695_6mA_reg', r'\textit{H.~pylori} 6mA'),
        ('arabidopsis_cpg_chr4', r'\textit{A.~thaliana} CpG 5mC'), ('arabidopsis_noncpg_chr4', r'\textit{A.~thaliana} non-CpG 5mC'),
        ('hg002_cpg', 'HG002 CpG 5mC'), ('rice_cpg', r'\textit{O.~sativa} CpG 5mC'), ('mouse_cpg', 'Mouse CpG 5mC'),
        ('syn_5mC', 'ONT oligos 5mC'), ('syn_5hmC', 'ONT oligos 5hmC'), ('syn_6mA', 'ONT oligos 6mA'), ('spo1_5hmU_reg', r'\phage 5hmU')]
ARMS = [('own1', 'sup'), ('hac1', 'hac'), ('fast1', 'fast'), ('own1-noref', 'sup'), ('hac1-noref', 'hac'), ('fast1-noref', 'fast')]


def cell(t, r, tag):
    a, c, f = t.loc[r, tag], t.loc[r, f'{tag}_called'], t.loc[r, f'{tag}_frac']
    return f'{a:.3f}' if f >= 0.999 else f'{a:.3f} ({c:.3f})'


def main(out=None):
    t = pd.read_csv(SRC, sep='\t').set_index('row')
    sub = t.loc[[r for r, _ in ROWS]]
    L = [r'% GENERATED by paper/supp_basecallers/make_table.py from paper/data/work/basecallers/compare_basecallers_refinement.tsv',
         r'\setlength{\tabcolsep}{3.5pt}%', r'\begin{tabular}{@{}l rr ccc ccc@{}}', r'\toprule',
         r' & & & \multicolumn{3}{c}{\textbf{refined boundaries}} & \multicolumn{3}{c}{\textbf{unrefined boundaries}} \\',
         r'\cmidrule(lr){4-6}\cmidrule(lr){7-9}',
         r'\textbf{Dataset} & $n_{+}$ & $n_{-}$ & ' + ' & '.join(rf'\textbf{{{n}}}' for _, n in ARMS) + r' \\', r'\midrule']
    for r, name in ROWS:
        npos = int(t.loc[r, 'n_pos']); nneg = int(t.loc[r, 'n_sites']) - npos
        L.append(f"{name} & {npos:,} & {nneg:,} & " + ' & '.join(cell(t, r, tag) for tag, _ in ARMS) + r' \\')
    L.append(r'\midrule')
    L.append(r'\textit{mean over datasets} & & & ' + ' & '.join(f"{sub[tag].mean():.3f}" for tag, _ in ARMS) + r' \\')
    L.append(r'\textit{mean over modifications} & & & ' + ' & '.join(f"{sub.groupby('chem')[tag].mean().mean():.3f}" for tag, _ in ARMS) + r' \\')
    L.append(r'\textit{mean over datasets, scored sites only} & & & ' + ' & '.join(f"{sub[f'{tag}_called'].mean():.3f}" for tag, _ in ARMS) + r' \\')
    L += [r'\bottomrule', r'\end{tabular}']
    out = Path(out) if out else TABLES / 'supp_basecallers.tex'
    out.parent.mkdir(parents=True, exist_ok=True); out.write_text('\n'.join(L) + '\n'); print('wrote', out)


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else None)
