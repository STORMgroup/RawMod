#!/usr/bin/env python3
"""Supplementary Table S2: the cost of every caller after the shared basecall, from one tool_cost.sh run.

  python make_cost_table.py [TIMING_TSV] [OUT.tex]   (defaults: the shipped paper/data/work/cost/tool_cost.tsv,
                                                      paper/tables/supp_cost.tex)

Rows: the shared basecall, then each tool's own cost after it. Columns: wall time, GPU busy time (utilization x
time), GPU energy, CPU time, peak host memory (summed PSS over every process of a stage) and peak GPU memory. A
multi-stage row sums wall, GPU busy, GPU energy and CPU over its stages and takes the maximum of the peaks.
"""
import os
import sys
from pathlib import Path

import pandas as pd

PAPER = Path(__file__).resolve().parents[1]
DEFAULT = PAPER / 'data' / 'work' / 'cost' / 'tool_cost.tsv'
DM = ['dorado_6mA@v3', 'dorado_4mC_5mC@v3', 'dorado_5mC_5hmC@v3', 'dorado_5mCG_5hmCG@v3']
ROWS = [  # (label, stages, modifications covered)
    (r'\baselinetool, 4 models, 4 passes', DM, '6mA, 4mC, 5(h)mC'),
    (r'\baselinetool, 4 models, 3 passes', ['dorado_6mA+4mC_5mC@v3', 'dorado_5mC_5hmC@v3', 'dorado_5mCG_5hmCG@v3'],
     '6mA, 4mC, 5(h)mC'),
    ('DeepMod2', ['deepmod2'], '5mCpG'),
    ('Rockfish', ['rockfish'], '5mCpG'),
    ('UniMeth, 2 models', ['unimeth_5mC', 'unimeth_6mA'], '5mC, 6mA'),
    (r'\sysname, GPU', ['rawmod_refine_x8', 'rawmod_fused_plus_x8_gpu', 'rawmod_fused_minus_x8_gpu'], 'any'),
    (r'\sysname, CPU only', ['rawmod_refine_x8', 'rawmod_fused_plus_x8_cpu', 'rawmod_fused_minus_x8_cpu'], 'any'),
]


def main(path, out):
    t = pd.read_csv(path, sep='\t').set_index('stage')

    def cells(stages):
        if any(s not in t.index for s in stages):
            return ' & '.join(['--'] * 6)
        s = t.loc[stages]
        v = [s.wall_s.sum() / 60, s.gpu_busy_s.sum() / 60, s.gpu_energy_j.sum() / 1e3, s.cpu_s.sum() / 3600,
             s.peak_pss_sum_kb.max() / 1024 ** 2, s.gpu_peak_mib.max() / 1024]
        return ' & '.join([f'{v[0]:.1f}', f'{v[1]:.1f}', f'{v[2]:.0f}', f'{v[3]:.2f}', f'{v[4]:.1f}', f'{v[5]:.1f}'])

    L = ['% GENERATED by paper/supp_cost/make_cost_table.py; do not edit by hand.',
         r'\setlength{\tabcolsep}{3.5pt}%', r'\begin{tabular}{@{}l l rrrrrr@{}}', r'\toprule',
         r'\textbf{Tool} & \textbf{Covers} & \textbf{\shortstack{Wall\\(min)}} & \textbf{\shortstack{GPU busy\\(min)}} & '
         r'\textbf{\shortstack{GPU energy\\(kJ)}} & \textbf{\shortstack{CPU\\(h)}} & \textbf{\shortstack{Peak RAM\\(GB)}} & '
         r'\textbf{\shortstack{GPU mem.\\(GB)}} \\',
         r'\midrule', rf"Shared basecall & -- & {cells(['dorado_basecall'])} \\", r'\midrule']
    L += [rf'{lab} & {mods} & {cells(st)} \\' for lab, st, mods in ROWS]
    L += [r'\bottomrule', r'\end{tabular}']
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(L) + '\n')
    print('\n'.join(L))
    print(f'-> {out}')


if __name__ == '__main__':
    a = sys.argv[1:]
    tables = Path(os.environ.get('RAWMOD_TABLES', PAPER / 'tables'))
    main(Path(a[0]) if a else DEFAULT, Path(a[1]) if len(a) > 1 else tables / 'supp_cost.tex')
