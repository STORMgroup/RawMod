#!/usr/bin/env python3
"""Supplementary dinoflagellate tables (composition control and feature contrasts) from dino_stats.json, dino_repeat_stats.json and dino_literature.json. Usage: make_dino_tables.py [OUT_DIR] (default: paper/tables)."""
import os as _os
from pathlib import Path as _Path
REPO = str(_Path(__file__).resolve().parents[2])
RAWMOD_RESULTS = _os.environ.get('RAWMOD_RESULTS') or f'{REPO}/paper/data/runs'  # training runs; shipped metrics by default
RAWMOD_DATA = _os.environ.get('RAWMOD_DATA', 'data')  # datasets (not shipped: set this to score raw signal)
RAWMOD_WORK = _os.environ.get('RAWMOD_WORK') or f'{REPO}/paper/data/work'  # outputs of the paper scripts; shipped by default

import sys, json
from pathlib import Path

F = Path(f'{RAWMOD_WORK}/dinoflagellate')
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(_os.environ.get('RAWMOD_TABLES') or f'{REPO}/paper/tables')
OUT.mkdir(parents=True, exist_ok=True)


def load(tag):
    d = F / tag
    return (json.load(open(d / 'dino_stats.json')), json.load(open(d / 'dino_repeat_stats.json')),
            json.load(open(d / f'dino_literature.json')))


# ------------------------------------------------------------------ context table (final model)
st, _, _ = load('out')
cats = ['intergenic', 'intron', 'UTR', 'CDS']
rows = [('observed', {k: st['categories'][k]['mean'] for k in cats}, None),
        ('5-mer residualised', st['context_adjusted']['5mer'], st['context_adjusted']['5mer']['r2']),
        ('local GC residualised', st['context_adjusted']['gc'], st['context_adjusted']['gc']['r2']),
        ('5-mer $\\times$ GC residualised', st['context_adjusted']['5mer_x_gc'], st['context_adjusted']['5mer_x_gc']['r2'])]
L = ['% GENERATED by figures/make_dino_tables.py (final model); source the analysis outputs dino_stats.json',
     r'\begin{tabular}{@{}l cccc c c@{}}', r'\toprule',
     r'& \textbf{intergenic} & \textbf{intron} & \textbf{UTR} & \textbf{CDS} & \textbf{IG/CDS} & \textbf{$R^2$ of context} \\',
     r'\midrule']
for name, v, r2 in rows:
    L.append(f"{name} & " + ' & '.join(f'{v[k]:.3f}' for k in cats) + f" & {v['intergenic'] / v['CDS']:.2f} & "
             + ('--' if r2 is None else f'{r2:.3f}') + r' \\')
L += [r'\bottomrule', r'\end{tabular}']
(OUT / 'supp_context.tex').write_text('\n'.join(L) + '\n')

# ------------------------------------------------------------------ both-models table
M = {t: load(t) for t in ('out',)}


def cells(fn):
    return ' & '.join(fn(*M[t]) for t in ('out',))


def ig_cds(st, rp, li):
    p = st['perm']['ig_cds']; v = st['categories']
    return f"{v['intergenic']['mean'] / v['CDS']['mean']:.2f}$\\times$ ($z{{=}}{p['z']:.1f}$)"


def ig_cds_adj(st, rp, li):
    a = [st['context_adjusted'][k]['fold_ig_vs_cds'] for k in ('5mer', 'gc', '5mer_x_gc')]
    return f'{min(a):.2f}--{max(a):.2f}$\\times$'


def intron_cds(st, rp, li):
    p = st['perm']['intron_cds']; v = st['categories']
    return f"{v['intron']['mean'] / v['CDS']['mean']:.2f}$\\times$ ($z{{=}}{p['z']:.1f}$)"


def young(st, rp, li):
    b0 = rp['by_divergence'][0]['mean']; u = rp['by_repeat_class']['unique']['mean']
    return f"{b0:.3f} vs.\\ {u:.3f}; $\\rho{{=}}{rp['rho_div_score_interspersed']:.2f}$ ($z{{=}}{rp['perm_rho_div']['z']:.1f}$)"


def rep_unique(st, rp, li):
    return f"$z{{=}}{rp['perm_repeat_minus_unique']['z']:.1f}$"


def exon(st, rp, li):
    e = li['exon_vs_flank']
    return f"{e['ratio']:.3f}$\\times$ ($z{{=}}{e['z']:.1f}$)"


def gstart(st, rp, li):
    e = li['gene_start_core_vs_ring']
    return f"{e['ratio']:.3f}$\\times$ ($z{{=}}{e['z']:.1f}$)"


def junc(kind):
    def f(st, rp, li):
        js = sorted((j for j in li['junctions'] if j['kind'] == kind), key=lambda j: j['start'])
        return ', '.join(f"{j['mean']:.2f} ({j['pct']:.0f})" for j in js)
    return f


def gc(st, rp, li):
    return f"$\\rho{{=}}{st['window10kb']['rho_vs_gc']:.2f}$"


ROWS = [
    ('Intergenic vs.\\ CDS', 'exons depleted \\cite{li_characterization_2024}', ig_cds),
    ('\\quad composition-adjusted', '', ig_cds_adj),
    ('Introns vs.\\ CDS', '--', intron_cds),
    ('Repeats ($\\le$5\\% div.) vs.\\ unique; score vs.\\ divergence', 'younger TEs carry more 5hmU \\cite{li_characterization_2024}', young),
    ('All interspersed repeats vs.\\ unique', 'TEs enriched \\cite{li_characterization_2024}', rep_unique),
    ('Exons vs.\\ $\\pm$1\\,kb flanks', 'depleted \\cite{li_characterization_2024}', exon),
    ('Gene start $\\pm$1\\,kb vs.\\ 1--5\\,kb', 'depleted (\\textit{B.~minutum}) \\cite{marinov_genomewide_2024}', gstart),
    ('Divergent strand switches: mean (percentile)', '--', junc('divergent')),
    ('Convergent strand switches: mean (percentile)', 'boundaries (\\textit{B.~minutum}) \\cite{marinov_genomewide_2024}', junc('convergent')),
    ('10\\,kb window score vs.\\ GC', '--', gc),
]
T = ['% GENERATED by figures/make_dino_tables.py; sources the analysis outputs dino_*.json',
     r'\setlength{\tabcolsep}{3pt}%',
     r'\begin{tabular}{@{}>{\RaggedRight}p{0.36\textwidth} >{\RaggedRight}p{0.30\textwidth} >{\RaggedRight}p{0.28\textwidth}@{}}',
     r'\toprule',
     r'\textbf{Comparison} & \textbf{Published finding} & \textbf{\sysname} \\',
     r'\midrule']
for name, prior, fn in ROWS:
    T.append(f'{name} & {prior} & {cells(fn)} \\\\')
T += [r'\bottomrule', r'\end{tabular}']
(OUT / 'supp_dino_models.tex').write_text('\n'.join(T) + '\n')
print((OUT / 'supp_context.tex').read_text()); print((OUT / 'supp_dino_models.tex').read_text())
