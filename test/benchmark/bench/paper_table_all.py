"""Table 1 of the preprint: every model on all 15 benchmark rows, on the page width.

    python -m bench.paper_table_all <tables_dir>/benchmark_models_full.tex <tables_dir>/benchmark_models_all.tex

Built from the full per-model table (paper_table.py) with the naming rules of paper_table_compact.py:
abbreviated two-line headers grouped by tool, scientific row names, matched rows marked and the 5mC
sub-groups merged. Unlike the compact table, no row is dropped. MethyNano is left out, because its
released pipeline does not reproduce its model (Supplementary Section S9.3); Supplementary Tables S21 and S22
keep it. The bottom rows are the mean and the worst of the five per-modification means and the
parameter count of each model, coloured on a log scale as in paper_table.py.
"""
import re
import sys

try:
    from . import paper_table_compact as C
    from .paper_table import param_cell
except ImportError:                       # run as a script from test/benchmark/bench
    import paper_table_compact as C
    from paper_table import param_cell

# (header text in the full table, group, line 1, line 2), output order: grouped by tool
COLUMNS = [
    (r'\sysname', 'ours', r'\sysname', ''),
    (r'Dorado\\4mC+5mC', 'released', 'Dor.', '4mC+5mC'),
    (r'Dorado\\5mC+5hmC', 'released', 'Dor.', '5(h)mC'),
    (r'Dorado\\5mCG+5hmCG', 'released', 'Dor.', '5(h)mCG'),
    (r'Dorado\\6mA', 'released', 'Dor.', '6mA'),
    (r'UniMeth\\5mC', 'released', 'UM', '5mC'),
    (r'UniMeth\\6mA', 'released', 'UM', '6mA'),
    (r'DeepMod2\\5mCG', 'released', 'DM2', '5mCG'),
    (r'Rockfish\\5mCG', 'released', 'RF', '5mCG'),
    (r'UniMeth-FT$^{\dagger}$\\4mC', 'finetuned', 'UM-FT', '4mC'),
    (r'UniMeth-FT$^{\dagger}$\\5hmC', 'finetuned', 'UM-FT', '5hmC'),
    (r'UniMeth-FT$^{\dagger}$\\5hmU', 'finetuned', 'UM-FT', '5hmU'),
    (r'UniMeth-Agn$^{\dagger}$\\all', 'finetuned', 'UM-Agn', 'all'),
    (r'Uncalled4$^{*}$\\vs.\ control', 'comparative', 'Unc4', 'control'),
    (r'NovaMod$^{*}$\\own control', 'comparative', 'NM', 'control'),
]


def _cells(line):
    return [c.strip() for c in line.rstrip().rstrip('\\').split('&')]


def main(src, dst):
    C.ALL_COLUMNS = COLUMNS
    C.COLUMNS = COLUMNS
    C.DROP = []
    C.CONTEXT = {('5mC, non-CpG', r'\textit{A.~thaliana}'): 'non-CpG'}

    # parameter counts at full precision, in output column order, for the log-scale colours
    full = [l for l in open(src).read().splitlines() if not l.startswith('%')]
    head = _cells(next(l for l in full if l.startswith(r'\textbf{Dataset}')))
    texts = [C.header_text(c) for c in head]
    praw = _cells(next(l for l in full if l.startswith('Parameters')))
    pvals = [praw[texts.index(t)] for t, *_ in COLUMNS]

    C.main(src, dst)
    lines = open(dst).read().splitlines()
    out = ['% GENERATED by test/benchmark/bench/paper_table_all.py from ' + src.split('/')[-1]
           + '; abbreviated two-line headers, every row, MethyNano left out.']
    for l in lines[1:]:
        if l.startswith(r'\resizebox') or l == '}':
            continue                                  # the table is set at the page width
        if l.startswith('Mean over the 15 rows'):
            continue                                  # the per-type mean and worst stay
        if l.startswith(r'\setlength{\tabcolsep}'):
            l = r'\setlength{\tabcolsep}{1.5pt}%'
        if l.startswith('Worst type &'):
            l = l.replace('Worst type &', r'\textbf{Worst type} &', 1)
        if l.startswith('Parameters &'):
            # colour and bold from the full-precision counts, text as rounded by the compact rules
            shown = [re.sub(r'^1\.24M$', '1.2M', v) for v in _cells(l)[1:]]   # two significant figures
            cells = []
            for v, s in zip(pvals, shown):
                if v == '--':
                    cells.append(s)
                    continue
                c = param_cell(v, pvals)
                color = re.match(r'\\cellcolor\{[^}]*\}', c).group(0)
                cells.append(color + (rf'\textbf{{{s}}}' if r'\textbf' in c else s))
            l = r'\textbf{Parameters} & ' + ' & '.join(cells) + r' \\'
        out.append(l)
    open(dst, 'w').write('\n'.join(out).rstrip('\n'))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
